facts = set()

# Get facts from user
n = int(input("Enter number of facts: "))

for i in range(n):
    p, x = input("Enter predicate and value: ").split()
    facts.add((p, x))

# Get rules
rules = []
m = int(input("Enter number of rules: "))

for i in range(m):
    print("Rule", i + 1)
    k = int(input("Enter number of premises: "))

    premises = []
    for j in range(k):
        p, x = input("Enter premise: ").split()
        premises.append((p, x))

    p, x = input("Enter conclusion: ").split()
    rules.append((premises, (p, x)))


def match(pattern, fact, sub):
    if pattern[0] != fact[0]:
        return None

    sub = sub.copy()

    if pattern[1].startswith("?"):
        v = pattern[1]

        if v in sub and sub[v] != fact[1]:
            return None

        sub[v] = fact[1]

    elif pattern[1] != fact[1]:
        return None

    return sub


def forward_chaining():
    changed = True

    while changed:
        changed = False

        for premises, conclusion in rules:
            subs = [{}]

            for p in premises:
                new_subs = []

                for sub in subs:
                    for fact in facts:
                        result = match(p, fact, sub)

                        if result is not None:
                            new_subs.append(result)

                subs = new_subs

            for sub in subs:
                new_fact = (
                    conclusion[0],
                    sub.get(conclusion[1], conclusion[1])
                )

                if new_fact not in facts:
                    facts.add(new_fact)
                    print("Derived:", new_fact)
                    changed = True

    query = tuple(input("\nEnter query: ").split())

    if query in facts:
        print("Query Proved!")
    else:
        print("Query Not Proved!")


forward_chaining()