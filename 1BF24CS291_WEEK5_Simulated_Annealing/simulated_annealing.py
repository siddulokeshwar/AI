import random
import math

def calculate_cost(state):
    n = len(state)
    cost = 0

    for i in range(n):
        for j in range(i + 1, n):
            if state[i] == state[j] or abs(state[i] - state[j]) == abs(i - j):
                cost += 1

    return cost


def generate_neighbours(state):
    n = len(state)
    neighbours = []

    for col in range(n):
        for row in range(n):
            if row != state[col]:
                neighbour = state.copy()
                neighbour[col] = row
                neighbours.append(neighbour)

    return neighbours


def simulated_annealing():
    n = int(input("Enter number of queens: "))

    if n < 1:
        print("Invalid N!")
        return

    current = [random.randrange(n) for _ in range(n)]
    T = 100
    cooling_rate = 0.9
    iteration = 1

    while T > 0.1 and iteration <= 10000:
        current_cost = calculate_cost(current)

        print("\nIteration:", iteration)
        print("Current State:", current)
        print("Current Cost:", current_cost)

        if current_cost == 0:
            break

        neighbours = generate_neighbours(current)

        # Select neighbour with least cost
        best_cost = min(calculate_cost(x) for x in neighbours)

        best_neighbours = [
            x for x in neighbours
            if calculate_cost(x) == best_cost
        ]

        next_state = random.choice(best_neighbours)
        next_cost = best_cost

        delta_E = current_cost - next_cost

        probability = 1 if delta_E > 0 else math.exp(delta_E / T)

        accepted = delta_E > 0 or random.random() < probability

        if accepted:
            current = next_state

        print("Selected Neighbour:", next_state)
        print("Neighbour Cost:", next_cost)
        print("Acceptance Probability:", round(probability, 4))
        print("Accepted:", accepted)

        T *= cooling_rate
        iteration += 1

    print("\n========== FINAL RESULT ==========")
    print("Final State:", current)
    print("Final Cost:", calculate_cost(current))

    if calculate_cost(current) == 0:
        print("Goal State Reached!")
    else:
        print("Solution not found.")


simulated_annealing()