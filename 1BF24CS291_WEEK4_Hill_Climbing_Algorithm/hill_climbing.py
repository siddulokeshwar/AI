def attacking_cost(state):
    conflicts = 0

    for i in range(4):
        for j in range(i + 1, 4):
            if state[i] == state[j] or abs(state[i] - state[j]) == abs(i - j):
                conflicts += 1

    return conflicts

def generate_neighbours(state):
    neighbours = []
    n = len(state)
    for cols in range(n):
        for row in range(cols + 1, n):
            new_state = state[:]
            new_state[cols], new_state[row] = new_state[row], new_state[cols]
            neighbours.append(new_state)

    return neighbours


def Hill_climbing():
    n = int(input("Enter the number of queens: "))
    current = list(map(int, input("Enter initial state: ").split()))

    if len(current) != n or sorted(current) != [i for i in range(n)]:
        print("Invalid input!")
        return

    iteration = 1

    while True:
        current_cost = calculate_cost(current)

        print("\nIteration:", iteration)
        print("Current State:", current)
        print("Current Cost:", current_cost)

        if current_cost == 0:
            print("Goal State Reached!")
            break

        neighbours = generate_neighbours(current)

        best_state = None
        best_cost = float('inf')

        for neighbour in neighbours:
            cost = attacking_cost(neighbour)

            print("Neighbour:", neighbour, "Cost:", cost)

            if cost < best_cost:
                best_cost = cost
                best_state = neighbour

        if best_cost >= current_cost:
            print("No better neighbour found!")
            break

        current = best_state
        iteration += 1

    print("\nFinal State:", current)
    print("Final Cost:", calculate_cost(current))


Hill_climbing()