import re

clauses = []
n = int(input("Enter number of clauses: "))

for i in range(n):
    c = input("Enter clause: ")
    clauses.append(re.split(r'\s+OR\s+', c, flags=re.I))

query = input("Enter query: ")
clauses.append(["NOT " + query])

def parse(s, k):
    s = s.strip()
    neg = s[:4].upper() == "NOT "
    if neg:
        s = s[4:].strip()
    p, a = s.split("(", 1)
    args = a.rstrip(")").split(",")
    args = [x.strip() for x in args]
    args = [f"?{x}_{k}" if x in "xyzuvw" and len(x) == 1 else x for x in args]
    return neg, p.strip(), args

def apply(x, sub):
    while x in sub:
        x = sub[x]
    return x

def unify(a, b, sub):
    for x, y in zip(a, b):
        x, y = apply(x, sub), apply(y, sub)
        if x == y:
            continue
        if x.startswith("?"):
            sub[x] = y
        elif y.startswith("?"):
            sub[y] = x
        else:
            return False
    return True

def resolve(c1, c2, i, j):
    a1 = [parse(x, i) for x in c1]
    a2 = [parse(x, j) for x in c2]

    for a in a1:
        for b in a2:
            n1, p1, x = a
            n2, p2, y = b

            if n1 == n2 or p1 != p2 or len(x) != len(y):
                continue

            sub = {}
            if unify(x, y, sub):
                result = []
                for neg, p, args in a1 + a2:
                    if (neg, p, args) == a or (neg, p, args) == b:
                        continue
                    args = [apply(v, sub) for v in args]
                    result.append(("NOT " if neg else "") + p + "(" + ",".join(args) + ")")
                return result
    return None

def resolution():
    while True:
        new = []
        for i in range(len(clauses)):
            for j in range(i + 1, len(clauses)):
                r = resolve(clauses[i], clauses[j], i+1, j+1)
                if r == []:
                    print("\nEmpty Clause Obtained!")
                    print("Query Proved!")
                    return
                if r is not None and r not in clauses and r not in new:
                    new.append(r)
        if not new:
            print("\nQuery Not Proved!")
            return
        clauses.extend(new)



resolution()