import itertools

symbols = ['A', 'B', 'C']

def is_kb_true(a, b, c):
    clause1 = a or b
    clause2 = (not a) or c
    clause3 = (not b) or c
    return clause1 and clause2 and clause3

def is_query_true(c):
    return c

print(" A     | B     | C     | KB_True | Query_True | KB_Entails_Query")
print("----------------------------------------------------------------")

entails = True
tt = {True: "True", False: "False"}

for A, B, C in itertools.product([True, False], repeat=3):
    kb = is_kb_true(A, B, C)
    query = is_query_true(C)

    row_entails = (not kb) or query

    print(f" {tt[A]:<5} | {tt[B]:<5} | {tt[C]:<5} | {tt[kb]:<7} | {tt[query]:<10} | {tt[row_entails]:<16}")


    if kb and not query:
        entails = False


print("----------------------------------------------------------------")
if entails:
    print("Result: KB entails the Query!")
else:
    print("Result: KB does NOT entail the Query.")